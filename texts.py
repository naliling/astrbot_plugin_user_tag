# ---------------------------------------------------------------- 组合函数

NL = chr(10)


def temp_usage(saved=""):
    """临时关系说明；已有存档关系时补一句不动存档。"""
    if not saved:
        return TEMP_USAGE
    return TEMP_USAGE + NL * 2 + "你现在存的是「" + saved + "」，临时关系不动它。"


def note_usage(max_len=60):
    """关系备注说明，附带当前字数上限。"""
    return NOTE_USAGE + NL * 2 + "（最多 " + str(max_len) + " 字）"
